/** Everything a section says, for search and for the coverage checks. */
export function sectionText(s: ManualSection): string {
  return [
    s.title, s.who, s.summary, ...(s.keywords ?? []), ...(s.tips ?? []),
    ...(s.steps ?? []).flatMap(st => [st.title, ...st.items]),
    ...(s.problems ?? []).flatMap(p => [p.problem, ...p.fix]),
  ].join('\n');
}

/** Sections matching a search, best first: title hits before body hits. Empty query = all. */
export function searchManual(query: string, sections: ManualSection[] = MANUAL_SECTIONS): ManualSection[] {
  const q = query.trim().toLowerCase();
  if (!q) return sections;
  const words = q.split(/\s+/).filter(Boolean);
  return sections
    .map(s => {
      const title = `${s.title} ${(s.keywords ?? []).join(' ')}`.toLowerCase();
      const body = sectionText(s).toLowerCase();
      if (!words.every(w => body.includes(w))) return null;
      return { s, score: words.filter(w => title.includes(w)).length };
    })
    .filter((x): x is { s: ManualSection; score: number } => x !== null)
    .sort((a, b) => b.score - a.score)
    .map(x => x.s);
}
